package com.example.engine

/**
 * Pure Kotlin AI & User Cross-TCG Combo Engine (Apex / Omni-Hybrid Synthesizer)
 * with ZERO Android or Compose imports.
 *
 * Strictly separate from the Flagship Ultimate TCG (`ULTIMATE_TCG_WIP`).
 * Enforces Copy-on-Fork whenever any GitHub-sourced locked base game (`upstreamSourceLock == true`)
 * is selected: the locked source game remains 100% immutable while a derived non-locked blueprint
 * (`originType = "AI_COMBO" | "USER_HYBRID"`, `upstreamSourceLock = false`, `derivedFromLockedIds`)
 * is synthesized and automatically eligible for MPV Card Maker coding export.
 */
data class CatalogBlueprint(
    val id: String,
    val name: String,
    val category: String,
    val originType: String,
    val boardArchetype: String,
    val upstreamSourceLock: Boolean,
    val requiresStrictBase: Boolean,
    val isBaseStandard: Boolean,
    val upstreamRepoUrl: String,
    val protocolHash: String,
    val clientTier: Int,
    val platforms: List<String>,
    val summary: String,
    val wipStatus: String = "",
    val suggestedForkId: String = "",
    val derivedFromLockedIds: List<String> = emptyList(),
    val mechanicModules: List<String> = emptyList()
)

enum class BoardArchetypeTemplate(
    val id: String,
    val displayLabel: String,
    val zoneCountSummary: String
) {
    ZONE_ROWS("zone-rows", "Zone Rows", "Monster / Spell-Trap / Dedicated Pendulum / Field rows"),
    BATTLEFIELD_STACK("battlefield-stack", "Battlefield + Stack", "Open permanents battlefield + LIFO Stack"),
    ACTIVE_BENCH_PRIZES("active-bench-prizes", "Active / Bench / Prizes", "Active lead + Bench slots + Prize/Point track"),
    TUG_OF_WAR_TRACK("tug-of-war-track", "Tug-of-War Track", "Shared Memory / Distance tug-of-war gauge"),
    MULTI_LANE_ARENA("multi-lane-arena", "Multi-Lane Arena", "3-to-7 parallel combat/location lanes"),
    TACTICAL_GRID("tactical-grid", "Tactical Grid", "2D/3D coordinate grid (3x6, 5x9, 7x7)"),
    FORMATION_AND_RANKS("formation-and-ranks", "Formation & Ranks", "Vanguard 6-Circle / Front-Back ranks / 3v3 Triangle"),
    ASYMMETRIC_OR_PATH("asymmetric-or-path", "Asymmetric / Path", "Expedition / Server-ICE / Adventure Path"),
    DECK_AS_LIFE("deck-as-life-or-combat-chain", "Deck-as-Life / Combat Chain", "Sequential combat chain or deck-as-health"),
    DIRECTIONAL_GRID("directional-and-territory-grid", "Directional Territory Grid", "3x3 / 4x4 / 3x5 directional capture & turf"),
    VIDEO_GAME_ACTION("video-game-action-or-roguelike", "Video-Game Action / Roguelike", "Intents, Sleights, Chips x Mult, Program Advance");

    companion object {
        val allIds: Set<String> = entries.mapTo(LinkedHashSet()) { it.id }
        fun fromId(id: String): BoardArchetypeTemplate =
            entries.firstOrNull { it.id == id } ?: MULTI_LANE_ARENA
    }
}

object ComboSynthesizer {
    val pluggableVideoGameModules: List<String> = listOf(
        "PXZ Pair/Solo/XP",
        "MvC Assist/Tag/Roman Cancel",
        "Fire Emblem Adjacency",
        "Slay the Spire Intents",
        "Battle Network Program Advance",
        "Triple Triad Directional Capture"
    )

    /**
     * Deterministically merges 2..4 selected games/formats + optional Video-Game Mechanic Modules
     * into a non-locked derived blueprint, strictly preserving locked GitHub sources via Copy-on-Fork.
     */
    fun synthesizeCustomCombo(
        comboTitle: String,
        selectedSources: List<CatalogBlueprint>,
        selectedModules: List<String>,
        isAiAutoGenerated: Boolean = false
    ): Result<CatalogBlueprint> {
        if (selectedSources.size !in 2..4) {
            return Result.failure(IllegalArgumentException("Select between 2 and 4 source games/formats to synthesize a combo."))
        }
        val cleanTitle = comboTitle.trim().take(80).ifEmpty {
            selectedSources.joinToString(" x ") { it.name.substringBefore(" (").take(18) }
        }
        val lockedAncestors = selectedSources
            .filter { it.upstreamSourceLock }
            .map { it.id }
            .distinct()

        // Choose dominant non-overlapping archetype deterministically
        val archetypes = selectedSources.map { it.boardArchetype }
        val resolvedArchetype = when {
            "tactical-grid" in archetypes -> "tactical-grid"
            "video-game-action-or-roguelike" in archetypes -> "video-game-action-or-roguelike"
            "formation-and-ranks" in archetypes -> "formation-and-ranks"
            "zone-rows" in archetypes && "battlefield-stack" in archetypes -> "multi-lane-arena"
            else -> archetypes.first()
        }

        val slug = cleanTitle.uppercase().replace(Regex("[^A-Z0-9]+"), "_").trim('_').take(28)
        val prefix = if (isAiAutoGenerated) "AI_COMBO" else "USER_HYBRID"
        val id = "${prefix}_${slug}_${selectedSources.size}X"

        val modules = selectedModules.ifEmpty {
            listOf(pluggableVideoGameModules.first())
        }.distinct()

        val summary = buildString {
            append("Merged ")
            append(selectedSources.joinToString(" + ") { it.name.substringBefore(" (") })
            append(". Modules: ")
            append(modules.joinToString(", "))
            if (lockedAncestors.isNotEmpty()) {
                append(". Copy-on-Fork from locked sources: ${lockedAncestors.joinToString(", ")}.")
            }
        }

        return Result.success(
            CatalogBlueprint(
                id = id,
                name = cleanTitle,
                category = "AI_COMBO",
                originType = if (isAiAutoGenerated) "AI_COMBO" else "USER_HYBRID",
                boardArchetype = resolvedArchetype,
                upstreamSourceLock = false,
                requiresStrictBase = false,
                isBaseStandard = false,
                upstreamRepoUrl = "",
                protocolHash = "sha256:${id.lowercase()}-v1.1",
                clientTier = 3,
                platforms = listOf("Android", "Web"),
                summary = summary,
                derivedFromLockedIds = lockedAncestors,
                mechanicModules = modules
            )
        )
    }

    /**
     * Deterministically generates a balanced AI Cross-TCG Combo from the loaded catalog without
     * mutating any locked GitHub source game.
     */
    fun autoGenerateBalancedAiCombo(
        catalog: List<CatalogBlueprint>,
        seedIndex: Int
    ): CatalogBlueprint {
        val safeCatalog = catalog.filter { it.id != "ULTIMATE_TCG_WIP" }
        if (safeCatalog.size < 3) {
            return CatalogBlueprint(
                id = "AI_COMBO_AUTO_FALLBACK",
                name = "Omni-Hybrid Resonance Arena",
                category = "AI_COMBO",
                originType = "AI_COMBO",
                boardArchetype = "multi-lane-arena",
                upstreamSourceLock = false,
                requiresStrictBase = false,
                isBaseStandard = false,
                upstreamRepoUrl = "",
                protocolHash = "sha256:ai-combo-auto-fallback-v1.1",
                clientTier = 3,
                platforms = listOf("Android", "Web"),
                summary = "Auto-generated balanced Cross-TCG combo.",
                mechanicModules = listOf("PXZ Pair/Solo/XP", "Slay the Spire Intents")
            )
        }
        val idx1 = (seedIndex * 7).mod(safeCatalog.size)
        val idx2 = (seedIndex * 13 + 5).mod(safeCatalog.size).let { if (it == idx1) (it + 1) % safeCatalog.size else it }
        val idx3 = (seedIndex * 19 + 11).mod(safeCatalog.size).let {
            if (it == idx1 || it == idx2) (it + 2) % safeCatalog.size else it
        }
        val picks = listOf(safeCatalog[idx1], safeCatalog[idx2], safeCatalog[idx3])
        val mod1 = pluggableVideoGameModules[seedIndex.mod(pluggableVideoGameModules.size)]
        val mod2 = pluggableVideoGameModules[(seedIndex + 2).mod(pluggableVideoGameModules.size)]
        val title = "Apex Synthesis #${seedIndex + 1}: ${picks[0].name.substringBefore(" ")} x ${picks[1].name.substringBefore(" ")}"
        return synthesizeCustomCombo(
            comboTitle = title,
            selectedSources = picks,
            selectedModules = listOf(mod1, mod2),
            isAiAutoGenerated = true
        ).getOrThrow()
    }
}
